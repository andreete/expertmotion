// Builds the onboarding-tour Sample Project media (ONBOARDING_TOUR §2 "Sample · Kafe Senja", API R-025):
//   resources/sample/clip-1.mp4, clip-2.mp4, clip-3.mp4   5 s each, 1280×720, H.264, no audio track, CRF 28
//   resources/sample/kafe-senja.srt                         5 Indonesian cues spanning the 15 s
//   resources/sample/README.txt                             CC0 1.0 dedication and provenance
// CC0 by construction: every frame is rendered by our own Engine (ExpertmotionTimeline, catalogue presets, bundled fonts); no
// third-party media. Build-time only. Needs the Engine bundle (npm run build:bundle -w @expertmotion/engine) and
// `tsc -b packages/engine`. Heavy: run inside the memory cap.
//   bash scripts/run-capped.sh node packages/engine/scripts/build-sample.mjs [--force]
import { ensureBrowser, renderMedia, selectComposition } from '@remotion/renderer';
import { applyOperations, createEmptyModel } from '@expertmotion/composition-model';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../', import.meta.url));   // also correct on Windows (build:all runs there)
const serveUrl = path.join(root, 'resources/engine/bundle');
const outDir = process.env.EM_SAMPLE_OUT ?? path.join(root, 'resources/sample');
const force = process.argv.includes('--force');
const gl = process.env.EM_GL ?? (process.platform === 'win32' ? 'angle' : 'swangle');
// Fixed Remotion serve port (never let it auto-pick the 3000 range; dev ports 4110/4120 are the service and UI).
const port = Number(process.env.EM_RENDER_PORT ?? 4130);
const opts = { chromiumOptions: { gl }, concurrency: 1, logLevel: 'error', port };
const log = (o) => console.log(JSON.stringify(o));
if (!fs.existsSync(path.join(serveUrl, 'index.html'))) { console.error('Engine bundle missing: npm run build:bundle -w @expertmotion/engine'); process.exit(1); }

const CLIP_MS = 5000;
const CLIPS = [
  { file: 'clip-1.mp4', palette: 'preset:palette.editorial-dark', background: 'preset:background.moving-gradient', title: 'Kafe Senja', sub: 'Kopi sore di sudut kota' },
  { file: 'clip-2.mp4', palette: 'preset:palette.pastel-friendly', background: 'preset:background.gradient', title: 'Kopi susu', sub: 'Gula aren · susu segar · espresso' },
  { file: 'clip-3.mp4', palette: 'preset:palette.neon-tech', background: 'preset:background.moving-gradient', title: 'Senja di kota', sub: 'Buka setiap hari, 16.00–22.00' },
];
const SRT = `1
00:00:00,500 --> 00:00:03,000
Selamat datang di Kafe Senja.

2
00:00:03,200 --> 00:00:06,000
Setiap sore kami menyeduh kopi susu segar.

3
00:00:06,200 --> 00:00:09,000
Gula aren asli, susu dingin, espresso pilihan.

4
00:00:09,200 --> 00:00:12,000
Duduk santai sambil menikmati senja di kota.

5
00:00:12,200 --> 00:00:14,800
Sampai jumpa di Kafe Senja!
`;
const README = `Expertmotion sample project "Kafe Senja" (onboarding tour)

Files: clip-1.mp4, clip-2.mp4, clip-3.mp4 (5 s each, 1280x720, H.264, no audio), kafe-senja.srt (5 Indonesian cues, 15 s).

Licence: CC0 1.0 Universal (public domain dedication), https://creativecommons.org/publicdomain/zero/1.0/
To the extent possible under law, the Expertmotion authors have waived all copyright and related or neighbouring rights to
these sample files. You may copy, modify and use them for any purpose without asking permission.

How they were made: generated by packages/engine/scripts/build-sample.mjs, which renders the Expertmotion Engine itself
(ExpertmotionTimeline with catalogue backgrounds, palettes and text presets, and the bundled open-licence fonts) through
Remotion. No camera footage, stock media or other third-party content is included. The subtitle text was written for
Expertmotion. Re-run the script to reproduce the files.
`;

let n = 0; const newId = () => `s${++n}`;
const apply = (m, ops) => { const r = applyOperations(m, ops, { assets: [], tier: 'T2', newId }); if (!r.ok) throw new Error(JSON.stringify(r.issues)); return r.value.model; };

fs.mkdirSync(outDir, { recursive: true });
await ensureBrowser();
const t0 = Date.now(); const out = [];
for (const c of CLIPS) {
  const file = path.join(outDir, c.file);
  if (!force && fs.existsSync(file)) { out.push({ file: c.file, skipped: true, bytes: fs.statSync(file).size }); continue; }
  const model = apply(createEmptyModel('sample', { autoRatio: false, ratio: '16:9', resolution: '720p', fps: 30, language: 'id' }), [
    { op: 'op:theme.set', args: { paletteId: c.palette } },
    { op: 'op:background.set', args: { presetId: c.background } },
    { op: 'op:text.add', args: { text: c.title, variant: 'preset:text.title', atMs: 0, durationMs: CLIP_MS } },
    { op: 'op:text.add', args: { text: c.sub, variant: 'preset:text.subtitle', atMs: 600, durationMs: CLIP_MS - 600 } },
    { op: 'op:project.setDurationPolicy', args: { policy: 'fixed', fixedMs: CLIP_MS } }]);
  const inputProps = { model, assets: {}, quality: 'full', watermark: false };
  const comp = await selectComposition({ serveUrl, id: 'ExpertmotionTimeline', inputProps, ...opts });
  const t = Date.now();
  await renderMedia({ composition: comp, serveUrl, codec: 'h264', crf: 28, muted: true, pixelFormat: 'yuv420p', outputLocation: `${file}.part.mp4`, inputProps, ...opts });
  fs.renameSync(`${file}.part.mp4`, file);
  out.push({ file: c.file, width: comp.width, height: comp.height, frames: comp.durationInFrames, seconds: (Date.now() - t) / 1000, bytes: fs.statSync(file).size });
  log(out[out.length - 1]);
}
fs.writeFileSync(path.join(outDir, 'kafe-senja.srt'), SRT);
fs.writeFileSync(path.join(outDir, 'README.txt'), README);
const total = fs.readdirSync(outDir).reduce((s, f) => s + fs.statSync(path.join(outDir, f)).size, 0);
log({ outDir, clips: out, totalBytes: total, seconds: (Date.now() - t0) / 1000, peakRssMb: Math.round(process.resourceUsage().maxRSS / 1024) });
