// Measures the advance widths (em) of the BUNDLED Inter faces (packages/engine/public/fonts, the files the Player and the renderer
// load) in Remotion's Chrome Headless Shell with canvas measureText, and writes src/inter-metrics.generated.ts for the text-box
// estimator (round 2, QA 2026-10-29 line breaks). Run on the Linux server: bash scripts/run-capped.sh node packages/composition-model/scripts/measure-inter.mjs
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
import { launch, openPage } from '../../../poc/browser/cdp.mjs';
const root = new URL('../../../', import.meta.url).pathname;
const fonts = `${root}packages/engine/public/fonts`;
const CHARS = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), ' ', '–', '—', '“', '”', '‘', '’', '…', '·', '±', '−', '×', '÷', '€', '£', '°', 'é', 'è', 'á', 'à', 'ó', 'í', 'ú', 'ñ', 'ü', 'ö', 'ä', '•', '→', '←', '↑', '↓', '✓'].join('');
const WEIGHTS = [400, 500, 600, 700, 800];
const PAIRS = ['AV', 'Av', 'AT', 'Ta', 'Te', 'To', 'Tr', 'Ty', 'Va', 'Ve', 'Vo', 'Wa', 'We', 'Ya', 'Yo', 'LT', 'LV', 'LY', 'P,', 'P.', 'T,', 'T.', 'V,', 'V.', 'Y,', 'Y.', 'r,', 'r.', 'y,', 'y.', 'ff', 'rt', 'ky', 'ek', 'ty'];
const server = http.createServer((req, res) => {
  const u = req.url.split('?')[0];
  if (u === '/') { res.writeHead(200, { 'Content-Type': 'text/html' }); return res.end('<!doctype html><meta charset="utf-8"><canvas id="c"></canvas>'); }
  const f = path.join(fonts, path.basename(u));
  if (!fs.existsSync(f)) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { 'Content-Type': 'font/woff2' }); fs.createReadStream(f).pipe(res);
}).listen(4116, '127.0.0.1');
const chrome = await launch(9341);
try {
  const p = await openPage(chrome.port, 'http://127.0.0.1:4116/', { width: 400, height: 300 });
  const out = await p.evaluate(`(async () => {
    const W = ${JSON.stringify(WEIGHTS)}, chars = ${JSON.stringify(CHARS)}, pairs = ${JSON.stringify(PAIRS)};
    for (const w of W) { const f = new FontFace('InterM', 'url(/inter-latin-' + w + '-normal.woff2)', { weight: String(w) }); await f.load(); document.fonts.add(f); }
    const ctx = document.getElementById('c').getContext('2d'); const res = {};
    for (const w of W) {
      ctx.font = w + ' 1000px InterM'; const row = {}; const kern = {};
      for (const ch of chars) row[ch] = Math.round(ctx.measureText(ch).width) / 1000;
      for (const pr of pairs) { const d = Math.round(ctx.measureText(pr).width) / 1000 - row[pr[0]] - row[pr[1]]; if (Math.abs(d) >= 0.005) kern[pr] = Math.round(d * 1000) / 1000; }
      res[w] = { row, kern, check: ctx.measureText('Ekspor nikel Indonesia, Jan–Agu 2026').width / 1000 };
    }
    return res;
  })()`);
  const lines = ['// GENERATED by packages/composition-model/scripts/measure-inter.mjs — do not edit. Advance widths (em) of the bundled Inter',
    '// faces (latin, normal), measured with canvas measureText in Chrome Headless Shell; KERN = pair adjustments (em) Chrome applies.',
    `export const INTER_WEIGHTS = ${JSON.stringify(WEIGHTS)} as const;`,
    `export const INTER_ADVANCE: Readonly<Record<number, Readonly<Record<string, number>>>> = ${JSON.stringify(Object.fromEntries(WEIGHTS.map((w) => [w, out[w].row])))};`,
    `export const INTER_KERN: Readonly<Record<number, Readonly<Record<string, number>>>> = ${JSON.stringify(Object.fromEntries(WEIGHTS.map((w) => [w, out[w].kern])))};`,
    `/** Chrome's own width (em) of "Ekspor nikel Indonesia, Jan–Agu 2026" per weight (test reference). */`,
    `export const INTER_CHECK: Readonly<Record<number, number>> = ${JSON.stringify(Object.fromEntries(WEIGHTS.map((w) => [w, Math.round(out[w].check * 10000) / 10000])))};`, ''];
  fs.writeFileSync(`${root}packages/composition-model/src/inter-metrics.generated.ts`, lines.join('\n'));
  console.log('written; check widths', Object.fromEntries(WEIGHTS.map((w) => [w, out[w].check])));
} finally { chrome.close(); server.close(); }
