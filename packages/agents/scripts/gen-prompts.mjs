// Extracts the versioned runtime prompts from SYSTEM_PROMPT.md (the owner) into src/prompts.generated.ts.
// Run after every SYSTEM_PROMPT.md change (DEFINITION_OF_DONE: prompt change). The packaging pipeline encrypts this module (ADR-007 B6).
import fs from 'node:fs';
const src = fs.readFileSync(new URL('../../../SYSTEM_PROMPT.md', import.meta.url), 'utf8');
const version = /prompt set v(\d+\.\d+\.\d+)/.exec(src)?.[1];
const block = (h) => { const part = src.split(`## ${h}`)[1]; if (!part) throw new Error(`missing ${h}`); const m = /```\n([\s\S]*?)```/.exec(part); if (!m) throw new Error(`no code block in ${h}`); return m[1].trimEnd(); };
const out = `// GENERATED by scripts/gen-prompts.mjs from SYSTEM_PROMPT.md — do not edit by hand.
export const PROMPT_SET_VERSION = ${JSON.stringify(version)};
export const BRAINSTORM_SYSTEM = ${JSON.stringify(block('P-1 Brainstorming Agent system prompt'))};
export const EDITOR_SYSTEM = ${JSON.stringify(block('P-2 Editor Agent system prompt'))};
export const SOCIAL_CAPTION_PROMPT = ${JSON.stringify(block('P-5 Social caption text and hashtags prompt'))};
`;
fs.writeFileSync(new URL('../src/prompts.generated.ts', import.meta.url), out);
console.log('prompts generated, version', version);
